
from django.db import models
from django.conf import settings
from django.core.validators import MinValueValidator


class RevenueTransaction(models.Model):
    """
    Revenue from a verified customer payment.
    """

    order = models.OneToOneField(
        "orders.Order",
        on_delete=models.PROTECT,
        related_name="revenue_transaction"
    )

    amount_paise = models.BigIntegerField(
        validators=[MinValueValidator(1)]
    )

    created_at = models.DateTimeField()

    def __str__(self):
        return f"Order {self.order_id} - {self.amount_paise} paise"


class SubtreeRevenue(models.Model):
    """
    Monthly revenue generated by a user's referral subtree.
    """

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT
    )

    month = models.DateField()

    amount_paise = models.BigIntegerField(default=0)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["user", "month"],
                name="unique_user_month_subtree_revenue"
            )
        ]

    def __str__(self):
        return f"{self.user_id} - {self.month}"


class MonthlyBonus(models.Model):
    """
    Record of monthly revenue share credited to a user.
    """

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT
    )

    month = models.DateField()

    amount_paise = models.BigIntegerField()

    created_at = models.DateTimeField(
        auto_now_add=True
    )

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["user", "month"],
                name="unique_user_month_bonus"
            )
        ]

    def __str__(self):
        return f"{self.user_id} - {self.month}"
